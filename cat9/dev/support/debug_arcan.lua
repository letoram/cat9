-- This table is generated by a simple appl enumerating _G, then we use that on the
-- global table to ignore entires that already exist in documentation. A possible
-- change would be to mark functions that are intercepted or use it to build tracesets
-- of functions (just eval(
-- 	local ot = {}; ot[sym] = sym;
-- 	sym = function(...) ot[sym] trigger_breakpoint(); return deb(...) end
-- )
--
local global_filter =
	loadfile(string.format("%s/cat9/dev/support/arcan_globals.lua", lash.scriptdir))()
local gen_local

local errors = {
	no_frame = "missing requested frame %d",
}

local synch_frame =
-- Arcan- specific debugger to cover both the needs of stepping
function(thread)
	if thread.state ~= "stopped" then
		return
	end

	thread.stack = {}
end

local function invalidate_threads(dbg)
	for k,thread in ipairs(dbg.data.threads) do
		for i=#thread.handlers.invalidated,1,-1 do
			thread.handlers.invalidated[i](thread)
		end
	end
end

local function ensure_thread(dbg, id)
	if dbg.data.threads[id] then
		return dbg.data.threads[id]
	end

	local th
	th = {
		id = id,
		state = "unknown",
		dbg = dbg,
		vmstack = {
			locals =
			function(_, cb)
				cb({locals = { variables = th.vmstack }})
			end
		},
		synch_frames = synch_frame,
		step = function(th)
			dbg.job.inp:write("stepnext\n")
			th.stack = {}
			th.state = "running"
		end,
		stepin = function(th)
			dbg.job.inp:write("stepcall\n")
			th.stack = {}
			th.state = "running"
		end,
		stepout = function(th)
			dbg.job.inp:write("stepend\n")
			th.stack = {}
			th.state = "running"
		end,
		freerun = function(th, mode, granularity)
		end,
		stepi = function(th)
			dbg.job.inp:write("stepinstruction\n")
			th.stack = {}
			th.state = "running"
		end,
		locals = function(th, fid, cb)
			local frame = th:frame(fid)
			if not frame then
				cb({error = string.format(errors.no_frame, fid or -1)})
			else
				frame:locals(cb)
			end
		end,
		frame = function(th, fid)
			if fid == -1 then
				return th.vmstack
			end

			for i=1,#th.stack do
				if th.stack[i].id == fid then
					return th.stack[i]
				end
			end
		end,
		stack = {},
		handlers = {
			invalidated = {}
		}
	}
	dbg.data.threads[id] = th
	return th
end

