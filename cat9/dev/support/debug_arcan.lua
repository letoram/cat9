if mode == "attach" then
	local job = {
		raw = "Arcan:Debug",
		short = "Arcan:Debug",
		block_buffer = true,
	}
	if not target[1] then
		return false, "missing output FIFO argument"
	end

	job.inp = lash.root:fopen(target[1], "w")
	if not job.inp then
		return false, "couldn't open " .. target[1]
	end

	local mon_outf = "/tmp/arcan.debug"
	job.out = lash.root:fopen(mon_outf, "fifo-in")

	if not job.out then
		job.inp:close()
		return false, "couldn't create output FIFO"
	end
	job.inp:write("output " .. mon_outf .. "\n")

-- since job doesn't have a pid yet it won't get processed in the normal job
-- dispatch, mark as deferred before importing and when the pid is set, unmark.
	cat9.import_job(job)
	debug.job = job
	local th = ensure_thread(debug, 1)
	th.state = "stopped"

	job.out:data_handler(
		function()
			local _, alive = cat9.flush_job(job, false, 100)
			if not alive then
				debug.log("closing attach handler")
				job.out:close()
			end
			return alive
		end
	)

	table.insert(job.hooks.on_data, thread_data_parser(debug, 1))
	table.insert(job.hooks.on_destroy, function()
		lash.root:funlink(mon_outf)
	end)

	return debug
end

