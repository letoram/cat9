local function get_frame_locals(debug, frame, cb)
	cb(
		{
			locals = { variables = frame.locals_tbl },
			globals = { variables = frame.globals_tbl }
		}
	)
end

local function frame_filter(frame, var, scope)
	if not frame.filters or not frame.filters[scope] then
		return
	end

	return frame.filters[scope][var.name] ~= nil
end

local function handler_for_tbl(debug, frame, var, cb, scope)
-- having a scope filter in presentation would be useful also outside global
--     global_filter[shmif.tblkey]
-- in order to highlight new/changed keys
	return
	function(key)
		var.variables = {}

-- we have table:index:tblkey:type:value | name
		for i,v in ipairs(key) do
			local shmif = string.unpack_shmif_argstr(v)
			local repack =
			{
				index = shmif.index,
				vartype = shmif.vartype,
				value = shmif.value,
				parent = val,
				name = shmif.tblkey,
				length = shmif.length,
				keys = shmif.keys,
				source = shmif.source,
				line = shmif.line and tonumber(shmif.line) or nil,
				line_end = shmif.line_end and tonumber(shmif.line_end) or nil
			}

-- for C functions we could just check name against the doc and get the
-- reference from there
			if shmif.vartype == "func" then
				repack.value = shmif.source or "function(C)"
			end

-- append accessor functions and let us recurse into hierarchies
			if not frame_filter(frame, repack, scope) then
				table.insert(
					var.variables, gen_local(debug, frame, repack, var, scope))
			end
		end
		cb(var)
	end
end

gen_local =
function(dbg, frame, shmif, parent, scope)
	local tbl =
	{
		ref = tonumber(shmif.index),
		type = shmif.vartype and shmif.vartype or "nil",
		value = shmif.value,
		parent = parent,
		name = shmif.name or "(missing)",
		modify =
		function(var, val)
			print("set", frame.id, shmif.index, val)
		end,
		fetch =
		function(var, cb)
			if var.type ~= "table" then
				cb(var.value or "nil")
			end

-- walk parents and build forward- list of indices
			table.insert(
				dbg.queue, {"TABLE", handler_for_tbl(dbg, frame, var, cb, scope)}
			)

			local tree = {tonumber(shmif.index)}

			local cv = var.parent
			while cv do
				table.insert(tree, 1, tostring(cv.ref))
				cv = cv.parent
			end

-- for global scope we don't want the id of the outmost variable as it is
-- just the container reference, and we want a filter-set that excludes the
-- known default arcan functions (with some caveat that if a function has
-- a non-C reference we want to see it as it means it is overwritten and
-- can be used as a possible breakpoint)
			local line
			if scope == "global" then
				line = "table g"
				if var.parent then
					table.remove(tree, 1)
					line = line .. " " .. table.concat(tree, " ")
				end
			elseif scope == "stack" then
				line =
					string.format("table s %s", table.concat(tree, " "))
			else
				line = string.format(
					"table l %d %s", frame.id, table.concat(tree, " "))
			end

		dbg.job.inp:write(line)
		dbg.job.inp:write("\n")
		end
	}

	if shmif.vartype == "table" then
		tbl.namedVariables = tonumber(shmif.length) + tonumber(shmif.keys)
	elseif not tbl.value then
		tbl.value = "nil"
	end

	return tbl
end

local function add_globals_wrapper(debug)
	return
		gen_local(
			debug, {id = -1, filters = {global = global_filter}},
			{
				index = 1,
				vartype = "table",
				name = "_G",
-- count isn't actually used in variables_view.lua
				length = 1,
				keys = 1,
			}, nil, "global"
		)
end

local key_handlers = {}
function key_handlers.BACKTRACE(debug, args, thread)
	local stack = thread.stack
	stack.entrypoint = "(unknown)"

	for i,v in ipairs(args) do
		local frame = {
			id = i,
			line = 0,
			line_end = 0,
			column = 0,
			pc = 0,
			thread = 0,
			name = "",
			locals = function(...)
				return get_frame_locals(debug, ...)
			end,
			filters = {
				global = global_filter
			},
			locals_tbl = {},
			globals_tbl = {add_globals_wrapper(debug)},
			source = "nop",
			path = "/tmp",
		}
		local shmif = string.unpack_shmif_argstr(v)
		if not shmif then
			debug.errors:add_line("Broken backtrace: " .. v)
			return
		end

-- some frames of anonymous inner functions we should resolve the outer name
-- afterwards as a fixup and propagate onwards
		if shmif.type == "stacktrace" then
			frame.path = shmif.source
			frame.source = frame.path
			frame.block_start = tonumber(shmif.start)
			frame.block_end = tonumber(shmif["end"])
			frame.line = tonumber(shmif.current)
			frame.line_end = current
			frame.name = shmif.name
			frame.id = tonumber(shmif.frame) or i
			table.insert(stack, frame)

		elseif shmif.type == "entrypoint" then
			stack.entrypoint = shmif.kind

		elseif shmif.type == "local" then
			table.insert(
				stack[#stack].locals_tbl,
				gen_local(debug, stack[#stack], shmif, nil, shmif.type))
		end
	end

-- fixup stack in reverse, propagate name into (null) named ones
	local lastname = stack.entrypoint
	for i=#stack,1,-1 do
		if stack[i].name == "(null)" then
			stack[i].name = lastname
		end
		lastname = stack[i].name
	end
end

function key_handlers.STACK(debug, args, thread)
	for i=#thread.vmstack, 1, -1 do
		table.remove(thread.vmstack, i)
	end

	for i,v in ipairs(args) do
		local shmif = string.unpack_shmif_argstr(v)
		if not shmif then
			debug.errors:add_line("Broken VM stack: " .. v)
			return
		end
		table.insert(
			thread.vmstack,
			gen_local(debug, {id = -1}, shmif, nil, "stack")
		)
	end
end

function key_handlers.ERROR(debug, args, thread)
	for _,v in ipairs(args) do
		local source, line, msg = string.match(v, "%[string%s(.+)%]%:(%d+):(.+)")
		if not source or not line or not msg then
			debug.errors:add_line(debug, "couldn't parse error message, raw:")
			debug.errors:add_line(debug, v)
		else
-- can get string.sub 2,-2 from source for the full filename
			debug.errors:add_line(debug, msg)
		end
	end
end

function key_handlers.SOURCE(debug, args, thread)
	debug.key.path = table.remove(debug.key, 1)
	debug.key.sourceReference = 0

	if debug.source_closure then
		debug.source_closure(table.concat(debug.key, "\n"))
		debug.source_closure = nil
	end
end

function key_handlers.BREAK(debug, args, thread)
	thread.breakpoints = {}

	for i,v in ipairs(args) do
		local shmif = string.unpack_shmif_argstr(v)
		if shmif and shmif.file and shmif.line then
			table.insert(thread.breakpoints, {
				id = i,
				verified = true,
				source = shmif.file,
				line = {tonumber(shmif.line)},
				path = shmif.file
			}
			);
		end
	end

-- merge into active set, this needs to extract / sort threads later
	debug.data.breakpoints = {}
	for i,v in ipairs(thread.breakpoints) do
		table.insert(debug.data.breakpoints, v)
	end
end

function process_key(debug, thread)
-- priority if the key matches a queued one
	if debug.queue[1] and debug.queue[1][1] == debug.key.name then
		local ent = table.remove(debug.queue, thread)
		ent[2](debug.key)
		return
	end

-- BEGINKV is special as its contents will depend on if we ran dumpstate or
-- dumpkeys, this is because how arcan-net does it based on exit status
		if key_handlers[debug.key.name] then
		key_handlers[debug.key.name](debug, debug.key, debug.data.threads[thread])
		return
	end

	print("unhandled key", debug.key.name)
end

